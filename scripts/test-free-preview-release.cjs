"use strict";

const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");

const root = path.join(__dirname, "..");
const read = (...parts) => fs.readFileSync(path.join(root, ...parts), "utf8");
const app = read("src", "App.jsx");
const server = read("server.cjs");
const nextServer = read("src", "server", "next-version.cjs");
const entitlements = read("src", "server", "subscription-entitlements.cjs");
const dockerfile = read("Dockerfile");
const compose = read("docker-compose.yml");
const sideBySideCompose = read("docker-compose.side-by-side.yml");
const dockerignore = read(".dockerignore");
const windowsInstaller = read("install", "windows", "Install-Homestead.ps1");
const windowsStarter = read("install", "windows", "Start-Homestead.ps1");
const releaseBuilder = read("scripts", "release", "build-free-preview.ps1");
const pkg = require(path.join(root, "package.json"));

assert.match(pkg.version, /^0\.6\.8\.\d+$/);
assert.match(nextServer, /edition: subscription\.tier/);
assert.match(nextServer, /app\.get\("\/api\/subscription\/status"/);
assert.match(nextServer, /app\.post\("\/api\/subscription\/playback"/);
assert.match(entitlements, /limits: \{ users: 1, concurrentStreams: 1 \}/);
assert.match(entitlements, /developmentPreview \? normalizeTier\(env\.HOMESTEAD_SUBSCRIPTION_TIER \|\| "pro"\) : "free"/);
assert.match(server, /app\.use\("\/api\/plugins", subscriptionService\.requireFeature\("plugins"\)\)/);
assert.match(server, /app\.use\("\/api\/livetv", subscriptionService\.requireFeature\("liveTV"\)\)/);
assert.match(server, /app\.use\("\/api\/adult", subscriptionService\.requireFeature\("adult"\)\)/);
assert.match(server, /app\.use\("\/api\/integrations", subscriptionService\.requireFeature\("externalIntegrations"\)\)/);
assert.match(server, /app\.post\("\/api\/setup\/test-integration", homesteadAccess\.requireOwner, subscriptionService\.requireFeature\("externalIntegrations"\)/);
assert.match(server, /app\.get\("\/api\/admin\/integration-health", homesteadAccess\.requireAdmin, subscriptionService\.requireFeature\("externalIntegrations"\)/);
assert.match(server, /if \(!subscriptionService\.has\("externalIntegrations"\)\)/);
assert.match(server, /storedConfig\.integrationSettings = \{\}/);
assert.match(app, /\/api\/subscription\/playback/);
assert.match(app, /setupConfig\?\.subscription\?\.features\?\.multiUser/);
assert.match(app, /Connected Services Are Not Included/);
assert.match(app, /settingsTab === "integrations" && integrationsAvailable/);
assert.match(app, /integrationsAvailable \? <MediaIntegrationsToolPage/);
assert.match(server, /express\.static\(path\.resolve\(process\.env\.MEDIA_ROOT \|\| "\/media"\)\)/);
assert.match(dockerfile, /RUN npm ci/);
assert.match(dockerfile, /HEALTHCHECK/);
assert.match(compose, /NODE_ENV:\s*"production"/);
assert.match(compose, /\.\/media:\/media/);
assert.match(sideBySideCompose, /container_name: homestead-free-preview/);
assert.match(sideBySideCompose, /\/media\/movies:ro/);
assert.doesNotMatch(sideBySideCompose, /\/media\/(?:photos|adult|inventory|livetv)/i);
assert.match(dockerignore, /^\/data$/m);
assert.match(dockerignore, /^\/media$/m);
assert(fs.existsSync(path.join(root, "INSTALL.md")));
assert(fs.existsSync(path.join(root, "install", "windows", "Install-Homestead.cmd")));
assert(fs.existsSync(path.join(root, "install", "windows", "Install-Homestead.ps1")));
assert(fs.existsSync(path.join(root, "install", "windows", "Start-Homestead.ps1")));
assert(fs.existsSync(path.join(root, "install", "windows", "Stop-Homestead.ps1")));
assert(fs.existsSync(path.join(root, "scripts", "release", "build-free-preview.ps1")));
assert.match(releaseBuilder, /AppLaunched=cmd\.exe \/d \/c Install-Homestead\.cmd/);
assert.doesNotMatch(releaseBuilder, /AppLaunched=.*Install Homestead\.cmd/);
assert.match(releaseBuilder, /homestead-windows-runtime\.zip/);
assert.match(releaseBuilder, /ffmpeg-static\\ffmpeg\.exe/);
assert.match(releaseBuilder, /ffprobe-static\\bin\\win32\\x64\\ffprobe\.exe/);
assert.doesNotMatch(windowsInstaller, /docker/i);
assert.match(windowsInstaller, /Start-Homestead\.ps1/);
assert.match(windowsStarter, /Start-Process -FilePath \$nodePath/);
assert.match(windowsStarter, /HOMESTEAD_FREE_PREVIEW/);

console.log("Homestead Free Preview packaging and entitlement checks passed.");
